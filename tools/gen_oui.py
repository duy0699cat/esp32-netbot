"""Build oui_table.h from the IEEE OUI registry CSV (oui.csv), keeping only common consumer vendors
so the table stays small enough for the ESP32's flash.

Usage:  python gen_oui.py path/to/oui.csv [output.h]
"""
import csv
import re
import sys

# (label shown in Telegram, regex matched against the registered organisation name)
VENDORS = [
    ("Apple", r"^Apple, Inc"),
    ("Samsung", r"^Samsung Electronics"),
    ("Xiaomi", r"Xiaomi"),
    ("Huawei", r"^(Huawei|HUAWEI)"),
    ("Espressif", r"^Espressif"),
    ("Intel", r"^Intel Corporate"),
    ("Realtek", r"^Realtek"),
    ("TP-Link", r"^TP-LINK|^TP-Link"),
    ("Google", r"^Google"),
    ("Amazon", r"^Amazon Technologies"),
    ("Sony", r"^Sony"),
    ("LG", r"^LG Electronics"),
    ("Microsoft", r"^Microsoft"),
    ("Raspberry Pi", r"^Raspberry Pi"),
    ("ASUS", r"^(ASUSTek|ASUSTEK)"),
    ("Gigabyte", r"^GIGA-BYTE"),
    ("MSI", r"^Micro-Star"),
    ("Dell", r"^Dell"),
    ("HP", r"^(Hewlett Packard|HP Inc)"),
    ("Lenovo", r"^Lenovo"),
    ("Tuya", r"^Tuya"),
    ("OPPO", r"Oppo|OPPO"),
    ("vivo", r"^vivo|^Vivo|BBK"),
    ("OnePlus", r"OnePlus"),
    ("Nintendo", r"^Nintendo"),
    ("Netgear", r"^NETGEAR"),
    ("D-Link", r"^D-Link"),
    ("Ubiquiti", r"^Ubiquiti"),
    ("Tenda", r"^Shenzhen Tenda"),
    ("Hikvision", r"^Hangzhou Hikvision"),
    ("VMware", r"^VMware"),
    ("Realme", r"^Realme|^Chongqing Fuhuan"),
    ("Murata", r"^Murata Manufacturing"),
    ("AzureWave", r"^AzureWave"),
    ("Liteon", r"^Liteon"),
]

csv_path = sys.argv[1]
out_path = sys.argv[2] if len(sys.argv) > 2 else "oui_table.h"
compiled = [(label, re.compile(rx)) for label, rx in VENDORS]
labels = [""] + [v[0] for v in VENDORS]

entries = {}
with open(csv_path, newline="", encoding="utf-8", errors="replace") as f:
    rd = csv.reader(f)
    next(rd, None)
    for row in rd:
        if len(row) < 3 or row[0] != "MA-L":
            continue
        try:
            prefix = int(row[1], 16)
        except ValueError:
            continue
        for i, (label, rx) in enumerate(compiled, start=1):
            if rx.search(row[2]):
                entries[prefix] = i
                break

table = [(v << 24) | p for p, v in sorted(entries.items())]  # sorted by prefix for binary search
with open(out_path, "w", encoding="utf-8") as o:
    o.write("#pragma once\n// Generated by tools/gen_oui.py from the IEEE OUI registry. Do not edit.\n")
    o.write("#include <stdint.h>\n#include <stddef.h>\n")
    o.write("static const char* const OUI_VENDORS[] = {" + ", ".join('"%s"' % l for l in labels) + "};\n")
    o.write("// each entry: (vendor_index << 24) | 24-bit OUI prefix, sorted by prefix\n")
    o.write("static const uint32_t OUI_TABLE[] = {\n")
    for i in range(0, len(table), 8):
        o.write("  " + ", ".join("0x%08X" % t for t in table[i:i + 8]) + ",\n")
    o.write("};\n")
    o.write("static const size_t OUI_COUNT = %d;\n" % len(table))
print("wrote %s: %d prefixes, ~%d KB flash" % (out_path, len(table), len(table) * 4 // 1024))
